/**
 * 주요 공약 detail page (P4-2, app/pledges/detail): the booklet's five
 * policy areas (V. 주요 공약, pp. 21–57). Each part opens with its
 * infographic — headline, sub-headline, the keywords in the centre circle
 * and four keyword boxes — redrawn without icons, without the three intro
 * lines and without the booklet's "세부 공약" block; every box item links down to
 * the pledge it summarises. The pledges below are cut down to one lead
 * sentence and the booklet's own bullet points, in its words.
 */

/** One link in a box line: its text and the pledge code ("1-1") it opens,
    or a part id for a line from the part's opening paragraph. */
export type PledgeLink = { text: string; to: string };

/** A box line. Usually one link; a line naming two pledges ("한마음의
    날·학내 소통 정례화") links each half to its own pledge. */
export type PledgeLine = PledgeLink[];

export type PledgeBox = { name: string; tagline: string; lines: PledgeLine[] };

/** `title`: "\n" marks where a long title breaks — after "및", or at a
    phrase boundary rather than wherever the column runs out (2026-10-18).
    A point starting "■ " is one of the booklet's subheadings over the
    points after it (3-9, 5-7); one starting "- " is a line under the
    point before it (1-8). */
export type Pledge = { code: string; title: string; lead: string; points: string[] };

export type PledgePart = {
  id: string;
  number: string;
  title: string;
  headline: string;
  subline: string;
  keywords: string;
  boxes: PledgeBox[];
  pledges: Pledge[];
};

/** Anchor of a pledge on the page. */
export const pledgeAnchor = (code: string) => `pledge-${code}`;

